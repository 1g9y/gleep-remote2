void draw_text(int x, int y, int scale, unsigned int color, const char *text)
{
    const char *c;
    for (c = text; *c; c++) {
        const char *p = strchr(KEY, *c);
        int idx = (p && *c != ' ') ? (int)(p - KEY) : 0;
        const unsigned char *g = GLYPHS[idx];
        int row, col;
        for (row = 0; row < 7; row++)
            for (col = 0; col < 5; col++)
                if (g[row] & (1 << (4 - col)))
                    vita2d_draw_rectangle(x + col * scale, y + row * scale,
                                          scale, scale, color);
        x += 6 * scale;
    }
}

int text_width(int scale, const char *text)
{
    return (int)strlen(text) * 6 * scale;
}